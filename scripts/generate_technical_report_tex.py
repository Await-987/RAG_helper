def formalize_report_content(content: str) -> str:
    replacements = sorted({**MODULE_REPLACEMENTS, **TEXT_REPLACEMENTS}.items(), key=lambda item: len(item[0]), reverse=True)
    for _ in range(2):
        for source, target in replacements:
            content = content.replace(source, target)
    content = re.sub(r"\b(?:backend|frontend|tools|scripts|config|data|docs)(?:/[A-Za-z0-9_.-]+)+", "相关功能模块", content)
    content = re.sub(r"\b[A-Za-z_][A-Za-z0-9_]*\.(?:py|tsx|ts|js|md|json)\b", "相关模块", content)
    content = content.replace("核心技术： & 多 Agent 编排、RAG、混合检索、MinerU 文档解析、知识图谱展示", "核心技术： & 多 Agent 编排、RAG、混合检索、MinerU 文档解析、知识图谱展示")
    return content


