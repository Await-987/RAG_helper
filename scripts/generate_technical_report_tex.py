def p(text: str = "") -> str:
    return textwrap.dedent(text).strip() + "\n\n"


def sentence(text: str) -> str:
    text = str(text).strip()
    if not text:
        return ""
    return text if text.endswith(("。", "；", "！", "？", ".", ";")) else text + "。"


def itemize(items):
    if not items:
        return ""
    clauses = [sentence(item).rstrip("。") for item in items if str(item).strip()]
    return p("该部分需要重点关注：" + "；".join(clauses) + "。")


def enumerate_block(items):
    if not items:
        return ""
    connectors = ["首先", "随后", "然后", "接着", "在此基础上", "进一步", "最后"]
    parts = []
    for idx, item in enumerate(items):
        connector = connectors[idx] if idx < len(connectors) else "同时"
        parts.append(f"{connector}，{sentence(item).rstrip('。')}")
    return p("。".join(parts) + "。")


def longtable(headers, rows, widths=None, caption=None):
    body = ""
    if caption:
        body += p(f"{caption}可用文字概括如下。")
    for row in rows:
        clean = [str(cell).strip() for cell in row]
        if not clean:
            continue
        if len(clean) == 1:
            body += p(sentence(clean[0]))
            continue
        subject_header = headers[0] if headers else "对象"
        subject = clean[0]
        clauses = []
        for header, value in zip(headers[1:], clean[1:]):
            if value:
                clauses.append(f"{header}为{value}")
        if clauses:
            body += p(f"围绕{subject_header}“{subject}”，" + "，".join(clauses) + "。")
        else:
            body += p(sentence(subject))
    return body


def detail_sections(topics):
    body = ""
    for idx, topic in enumerate(topics, 1):
        title = topic["title"]
        focus = topic["focus"]
        checkpoints = topic["checkpoints"]
        risks = topic.get("risks", "如果该部分设计与验证结果不一致，验收时应以接口行为、运行记录和评测结果为准，并将未形成闭环的内容调整为后续计划。")
        body += subsection(title, p(f"""
        本节从框架设计角度展开说明“{title}”。该部分的设计重点是：{focus}。报告正文需要直接解释这些细节，而不是把它们集中放在附录中，因为这些内容决定了系统是否真正可验证、可排查、可扩展。对于电网工程智能助手而言，技术路线只有落到模块边界、接口行为、状态流转和质量约束上，才具有报告层面的技术说服力。

        风险说明：{risks}
        """) + itemize(checkpoints))
    return body


